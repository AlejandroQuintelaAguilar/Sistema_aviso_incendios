-- Iteración 3: Gestión de Brigadas.
-- Las tablas ya existen en Neon; este archivo las documenta y permite crearlas
-- en una base limpia. Es aditivo e idempotente: no modifica tablas de otros módulos.
-- `incidente_brigadas` pertenece a la iteración 5 (Incidentes) y NO se crea aquí.

CREATE TABLE IF NOT EXISTS brigadas (
    id_brigada     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    estado         VARCHAR(30)  NOT NULL DEFAULT 'ACTIVA',
    motivo_estado  TEXT,
    id_estacion    INTEGER NOT NULL REFERENCES estaciones (id_estacion) ON DELETE RESTRICT,
    created_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT brigadas_estado_check
        CHECK (estado IN ('ACTIVA', 'EN_OPERACION', 'DESCANSO', 'DISUELTA'))
);

CREATE TABLE IF NOT EXISTS brigada_miembros (
    id_brigada_miembro  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_brigada          INTEGER NOT NULL REFERENCES brigadas (id_brigada) ON DELETE CASCADE,
    id_persona          INTEGER NOT NULL REFERENCES personas (id_persona) ON DELETE RESTRICT,
    rol_en_brigada      VARCHAR(50),
    fecha_incorporacion DATE,
    estado              VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT brigada_miembros_rol_en_brigada_check
        CHECK (rol_en_brigada IN
               ('JEFE_CUADRILLA', 'BOMBERO', 'ESPECIALISTA', 'PARAMEDICO')),
    CONSTRAINT brigada_miembros_estado_check
        CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT brigada_miembros_id_brigada_id_persona_key
        UNIQUE (id_brigada, id_persona)
);

CREATE INDEX IF NOT EXISTS idx_brigada_miembros_brigada
    ON brigada_miembros (id_brigada);
CREATE INDEX IF NOT EXISTS idx_brigada_miembros_persona
    ON brigada_miembros (id_persona);
